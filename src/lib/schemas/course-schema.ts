import { z } from "zod";
import type { Course } from "@/lib/types";

/**
 * ฟังก์ชันสร้าง Zod Schema สำหรับตรวจสอบข้อมูลในฟอร์มเพิ่มวิชา
 * @param courses อาร์เรย์ของวิชาที่มีอยู่ใน Store เพื่อใช้ตรวจสอบรหัสวิชาซ้ำ
 */
export const createCourseFormSchema = (courses: Course[] = []) =>
  z.object({
    // -------------------------------------------------------------
    // ข้อ 1.3: ตรวจสอบรหัสวิชา
    // -------------------------------------------------------------
    courseCode: z
      .string()
      .trim() // ตัดช่องว่างหน้า-หลัง
      .regex(/^\d{6}$/, "รหัสวิชาต้องเป็นตัวเลข 6 หลัก") // ตรวจสอบว่าเป็นตัวเลขครบ 6 หลักพอดี
      .refine(
        // ใช้ .refine เพื่อเช็คว่ารหัสวิชาที่กรอก ซ้ำกับ courseId ที่มีอยู่แล้วหรือไม่
        (code) => !courses.some((course) => course.courseId === code),
        {
          message: "รหัสวิชานี้มีอยู่แล้ว", // ข้อความแจ้งเตือนเมื่อรหัสซ้ำ
        }
      ),

    // -------------------------------------------------------------
    // ข้อ 1.3: ตรวจสอบชื่อวิชา
    // -------------------------------------------------------------
    courseName: z
      .string()
      .trim() // ตัดช่องว่าง
      .min(1, "ห้ามมีค่าว่าง") // ต้องไม่เป็นค่าว่าง
      .max(100, "มีความยาวไม่เกิน 100 ตัวอักษร"), // ยาวไม่เกิน 100 ตัวอักษร

    // -------------------------------------------------------------
    // ข้อ 2.1, 2.2, 2.3: ตรวจสอบข้อมูลผู้สอน (Array Fields)
    // -------------------------------------------------------------
    instructors: z
      .array(
        z.object({
          // ข้อ 2.2: ชื่อผู้สอนห้ามว่าง
          name: z.string().trim().min(1, "กรุณากรอกชื่อผู้สอน"),
          // ข้อ 2.2: รูปแบบอีเมลถูกต้อง และต้องลงท้ายด้วย @cmu.ac.th
          email: z
            .string()
            .trim()
            .email("รูปแบบอีเมลไม่ถูกต้อง")
            .endsWith("@cmu.ac.th", "ต้องเป็นอีเมล @cmu.ac.th"),
        })
      )
      .min(1, "ต้องมีผู้สอนอย่างน้อย 1 คน") // มีผู้สอนอย่างน้อย 1 คน
      .max(3, "มีผู้สอนได้ไม่เกิน 3 คน") // ข้อ 2.1: ผู้สอนได้สูงสุดไม่เกิน 3 คน
      // ข้อ 2.3: ตรวจสอบอีเมลผู้สอนห้ามซ้ำกันในรายการ
      .refine(
        (instructors) => {
          // ดึงอีเมลทั้งหมดมาตัดช่องว่าง แปลงเป็นตัวพิมพ์เล็ก และคัดกรองเฉพาะตัวที่มีค่า
          const emails = instructors
            .map((ins) => ins.email.trim().toLowerCase())
            .filter((email) => email.length > 0);
          // ใช้ Set ตรวจสอบจำนวน ถ้า Set เล็กกว่า Array แสดงว่ามีค่าซ้ำ
          return new Set(emails).size === emails.length;
        },
        {
          message: "อีเมลผู้สอนซ้ำกัน", // แสดงข้อความ error เมื่ออีเมลซ้ำ
        }
      ),

    // -------------------------------------------------------------
    // ข้อ 3.1: ชื่อหลักสูตร (ต้องเลือก CPE หรือ ISNE)
    // -------------------------------------------------------------
    program: z.enum(["CPE", "ISNE"], {
      message: "เลือกหลักสูตร",
    }),

    // -------------------------------------------------------------
    // ข้อ 3.2: ภาคการศึกษา (ต้องเลือก ภาค 1, ภาค 2 หรือ ภาค 3/ฤดูร้อน)
    // -------------------------------------------------------------
    semester: z.enum(["1", "2", "3"], {
      message: "เลือกภาคการศึกษา",
    }),

    // -------------------------------------------------------------
    // ข้อ 3.3: รายละเอียด (ไม่บังคับกรอก แต่ถ้ากรอกห้ามเกิน 100 ตัวอักษร)
    // -------------------------------------------------------------
    description: z
      .string()
      .max(100, "รายละเอียดต้องมีความยาวไม่เกิน 100 ตัวอักษร"),

    // -------------------------------------------------------------
    // ข้อ 3.4: รับข่าวสารทางอีเมล (ค่า Boolean)
    // -------------------------------------------------------------
    notifyByEmail: z.boolean(),
  });

// ข้อ 1.1: ใช้ z.infer สร้าง Type อัตโนมัติจาก Schema โดยไม่ต้องประกาศ interface ซ้ำเอง
export type CourseFormValues = z.infer<ReturnType<typeof createCourseFormSchema>>;